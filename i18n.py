DEFAULT_LANG = 'ru'


def t(tg_id: int, key: str, **kwargs) -> str:
    """Get a translated string for the given tg_id's language."""
    lang = db.get_user_language(tg_id)
    strings = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG])
    text = strings.get(key) or TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError):
            pass
    return text


def get_strings(lang: str) -> dict:
    """Get all strings for the given language code."""
    return TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG])
